# Generates a fresh release keystore for ClimateSphere and writes android/keystore.properties.
# Run from anywhere: powershell -ExecutionPolicy Bypass -File scripts/generate-signing-key.ps1
#
# The keystore and properties file are gitignored. Back them up somewhere safe:
# losing this key means you can no longer publish updates to the same app listing.

param(
    [string]$Alias = "climate-release",
    [string]$StoreFile = "climate-release.jks",
    [string]$DName = "CN=ClimateSphere, OU=Release, O=ClimateSphere, L=Unknown, ST=Unknown, C=IN"
)

$ErrorActionPreference = "Stop"

$androidDir = Join-Path (Split-Path -Parent $PSScriptRoot) "android"
$keystorePath = Join-Path $androidDir $StoreFile
$propertiesPath = Join-Path $androidDir "keystore.properties"

if (Test-Path $keystorePath) {
    throw "Refusing to overwrite existing keystore at $keystorePath. Move it aside first."
}

$keytool = Join-Path $env:JAVA_HOME "bin\keytool.exe"
if (-not (Test-Path $keytool)) {
    $keytool = "keytool"
}

# 24 bytes -> 32 URL-safe characters of entropy.
$bytes = New-Object byte[] 24
[System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
$password = [Convert]::ToBase64String($bytes).Replace("+", "-").Replace("/", "_").TrimEnd("=")

& $keytool -genkeypair `
    -keystore $keystorePath `
    -alias $Alias `
    -keyalg RSA `
    -keysize 4096 `
    -validity 10000 `
    -storepass $password `
    -keypass $password `
    -dname $DName

if ($LASTEXITCODE -ne 0) {
    throw "keytool failed with exit code $LASTEXITCODE"
}

@"
# Generated by scripts/generate-signing-key.ps1. Do not commit.
storeFile=$StoreFile
storePassword=$password
keyAlias=$Alias
keyPassword=$password
"@ | Set-Content -Path $propertiesPath -Encoding UTF8

Write-Host "Created $keystorePath"
Write-Host "Created $propertiesPath"
Write-Host "Back up both files. The password is stored in keystore.properties."
