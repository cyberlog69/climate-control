#!/usr/bin/env bash
# Generates a fresh release keystore for ClimateSphere and writes android/keystore.properties.
# Both files are gitignored. Back them up: losing this key blocks future app updates.
set -euo pipefail

ALIAS="${ALIAS:-climate-release}"
STORE_FILE="${STORE_FILE:-climate-release.jks}"
DNAME="${DNAME:-CN=ClimateSphere, OU=Release, O=ClimateSphere, L=Unknown, ST=Unknown, C=IN}"

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ANDROID_DIR="$(dirname "$SCRIPT_DIR")/android"
KEYSTORE_PATH="$ANDROID_DIR/$STORE_FILE"
PROPERTIES_PATH="$ANDROID_DIR/keystore.properties"

if [ -e "$KEYSTORE_PATH" ]; then
  echo "Refusing to overwrite existing keystore at $KEYSTORE_PATH. Move it aside first." >&2
  exit 1
fi

KEYTOOL="${JAVA_HOME:+$JAVA_HOME/bin/}keytool"
PASSWORD="$(LC_ALL=C tr -dc 'A-Za-z0-9_-' < /dev/urandom | head -c 32)"

"$KEYTOOL" -genkeypair \
  -keystore "$KEYSTORE_PATH" \
  -alias "$ALIAS" \
  -keyalg RSA \
  -keysize 4096 \
  -validity 10000 \
  -storepass "$PASSWORD" \
  -keypass "$PASSWORD" \
  -dname "$DNAME"

umask 077
cat > "$PROPERTIES_PATH" <<EOF
# Generated by scripts/generate-signing-key.sh. Do not commit.
storeFile=$STORE_FILE
storePassword=$PASSWORD
keyAlias=$ALIAS
keyPassword=$PASSWORD
EOF

echo "Created $KEYSTORE_PATH"
echo "Created $PROPERTIES_PATH"
echo "Back up both files. The password is stored in keystore.properties."
